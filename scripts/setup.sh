#!/usr/bin/env bash
# wp-memlog — One-command setup script
# Usage: ./scripts/setup.sh [--quick | --full | --reset]
set -euo pipefail

# ── Colors ──────────────────────────────────────────────
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

# ── Paths ───────────────────────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
ENV_FILE="$PROJECT_DIR/.env"
ENV_EXAMPLE="$PROJECT_DIR/.env.example"

# ── Helpers ─────────────────────────────────────────────
log_info()  { echo -e "${BLUE}[INFO]${NC}  $*"; }
log_ok()    { echo -e "${GREEN}[OK]${NC}    $*"; }
log_warn()  { echo -e "${YELLOW}[WARN]${NC}  $*"; }
log_error() { echo -e "${RED}[ERROR]${NC} $*"; }
log_step()  { echo -e "\n${BOLD}${CYAN}━━━ $* ━━━${NC}"; }

die() { log_error "$*"; exit 1; }

spinner() {
    local pid=$1 msg=$2
    local spin='⠋⠙⠹⠸⠼⠴⠦⠶⠲⠳'
    local i=0
    while kill -0 "$pid" 2>/dev/null; do
        i=$(( (i+1) % 10 ))
        printf "\r${YELLOW}%s${NC} %s" "${spin:$i:1}" "$msg"
        sleep 0.1
    done
    wait "$pid" 2>/dev/null
    local rc=$?
    printf "\r%-40s\n" " "
    return $rc
}

check_cmd() {
    command -v "$1" &>/dev/null
}

gen_key() {
    openssl rand -hex 32 2>/dev/null || head -c 64 /dev/urandom | xxd -p | head -c 64
}

gen_password() {
    openssl rand -base64 24 2>/dev/null | tr -d '=+/' | head -c 24
}

# ── Pre-flight checks ──────────────────────────────────
preflight() {
    log_step "Pre-flight checks"

    local ok=true
    check_cmd docker      || { log_error "Docker is not installed"; ok=false; }
    check_cmd docker      || true
    (docker compose version &>/dev/null || docker-compose version &>/dev/null) \
                              || { log_error "Docker Compose is not installed"; ok=false; }
    check_cmd python3     || { log_error "Python 3 is not installed"; ok=false; }
    check_cmd curl        || { log_error "curl is not installed"; ok=false; }
    check_cmd openssl     || { log_error "openssl is not installed"; ok=false; }

    # Python version check
    local pyver
    pyver=$(python3 -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')
    if python3 -c "import sys; exit(0 if sys.version_info >= (3,10) else 1)" 2>/dev/null; then
        log_ok "Python $pyver"
    else
        log_error "Python 3.10+ required (found $pyver)"
        ok=false
    fi

    $ok || die "Pre-flight checks failed. Install missing dependencies and retry."
    log_ok "All pre-flight checks passed"
}

# ── Step 1: Environment file ───────────────────────────
setup_env() {
    log_step "Step 1: Environment configuration"

    if [[ -f "$ENV_FILE" ]]; then
        log_warn ".env already exists"
        read -rp "  Overwrite? (y/N): " ans
        [[ "${ans,,}" == "y" ]] || { log_info "Keeping existing .env"; return 0; }
    fi

    log_info "Generating secure keys and passwords..."

    local meili_master meili_search mysql_root wp_db wp_admin
    meili_master=$(gen_key)
    meili_search=$(gen_key)
    mysql_root=$(gen_password)
    wp_db=$(gen_password)
    wp_admin=$(gen_password)

    cat > "$ENV_FILE" <<EOF
# wp-memlog environment variables
# ⚠️  Generated by setup.sh — DO NOT commit to git!

# Project
COMPOSE_PROJECT_NAME=wp-memlog

# ============================================
# MEILISEARCH
# ============================================
MEILI_MASTER_KEY=${meili_master}
MEILI_NO_ANALYTICS=true
MEILI_SEARCH_KEY=${meili_search}

# ============================================
# MARIADB
# ============================================
MYSQL_ROOT_PASSWORD=${mysql_root}
MYSQL_DATABASE=wp_memlog
MYSQL_USER=wp
MYSQL_PASSWORD=${wp_db}
MYSQL_CHARSET=utf8mb4
MYSQL_COLLATION=utf8mb4_unicode_ci

# ============================================
# WORDPRESS
# ============================================
WORDPRESS_DB_HOST=db
WORDPRESS_DB_USER=wp
WORDPRESS_DB_PASSWORD=${wp_db}
WORDPRESS_DB_NAME=wp_memlog
WP_ADMIN_PASSWORD=${wp_admin}

# ============================================
# WP-MEMLOG COLLECTOR
# ============================================
WP_MEMLOG_WP_URL=http://127.0.0.1:8080
WP_MEMLOG_WP_USER=admin
WP_MEMLOG_WP_APPPW=${wp_admin}
WP_MEMLOG_MEILI_URL=http://127.0.0.1:7700
WP_MEMLOG_MEILI_KEY=${meili_search}

# ============================================
# OPENROUTER (optional — for AI summarization)
# ============================================
# OPENROUTER_API_KEY=sk-or-v1-...

# ============================================
# MONITORING (optional — Telegram alerts)
# ============================================
# TG_TOKEN=
# TG_CHAT_ID=
EOF

    chmod 600 "$ENV_FILE"
    log_ok ".env created with secure random keys"
    log_info "  WP Admin URL: http://127.0.0.1:8080/wp-admin"
    log_info "  WP Username:  admin"
    log_info "  WP Password:  $wp_admin"
    echo ""
    log_warn "  Save the WP password above — it won't be shown again!"
}

# ── Step 2: Docker containers ──────────────────────────
setup_docker() {
    log_step "Step 2: Starting Docker containers"

    cd "$PROJECT_DIR"

    log_info "Pulling images..."
    docker compose pull 2>&1 | tail -5

    log_info "Starting containers..."
    docker compose up -d

    log_info "Waiting for containers to be healthy..."
    local max_wait=120 waited=0
    while [[ $waited -lt $max_wait ]]; do
        local all_healthy=true
        for svc in meilisearch wordpress db; do
            local status
            status=$(docker inspect --format='{{.State.Health.Status}}' "wp-memlog-${svc}" 2>/dev/null || echo "starting")
            if [[ "$status" != "healthy" ]]; then
                all_healthy=false
                break
            fi
        done
        $all_healthy && break
        sleep 5
        waited=$((waited + 5))
        printf "\r  Waiting... %ds / %ds" "$waited" "$max_wait"
    done
    echo ""

    # Verify
    for svc in meilisearch wordpress db; do
        local status
        status=$(docker inspect --format='{{.State.Health.Status}}' "wp-memlog-${svc}" 2>/dev/null || echo "unknown")
        if [[ "$status" == "healthy" ]]; then
            log_ok "  $svc: healthy"
        else
            log_error "  $svc: $status (timeout)"
            die "Container $svc failed to become healthy. Check: docker logs wp-memlog-${svc}"
        fi
    done
}

# ── Step 3: WordPress installation ─────────────────────
setup_wordpress() {
    log_step "Step 3: WordPress installation"

    local wp="docker exec wp-memlog-wp wp --allow-root"

    # Check if already installed
    if $wp core is-installed 2>/dev/null; then
        log_warn "WordPress already installed, skipping"
    else
        log_info "Installing WordPress..."
        $wp core install \
            --url="http://127.0.0.1:8080" \
            --title="wp-memlog" \
            --admin_user="admin" \
            --admin_password="${WP_ADMIN_PASSWORD:-$(grep WP_ADMIN_PASSWORD "$ENV_FILE" | cut -d= -f2)}" \
            --admin_email="admin@wp-memlog.local" \
            --skip-email 2>&1 | tail -3
        log_ok "WordPress installed"
    fi

    # Permalinks
    log_info "Setting permalink structure..."
    $wp rewrite structure '/%postname%/' --hard 2>/dev/null
    log_ok "Permalinks: /%postname%/"

    # Create categories
    log_info "Creating agent categories..."
    for cat in deus macguffin hubris; do
        if ! $wp term list category --slug="$cat" --field=slug 2>/dev/null | grep -q "$cat"; then
            $wp term create category "$cat" 2>/dev/null && log_ok "  category: $cat" || log_warn "  category: $cat (may already exist)"
        else
            log_ok "  category: $cat (exists)"
        fi
    done

    # Create custom roles
    log_info "Creating custom roles..."
    $wp eval '
    if (!get_role("memlog_writer")) {
        add_role("memlog_writer", "Memlog Writer", [
            "read" => true,
            "edit_posts" => true,
            "publish_posts" => true,
            "read_private_posts" => true,
            "edit_private_posts" => true,
            "delete_posts" => false,
        ]);
    }
    if (!get_role("memlog_reader")) {
        add_role("memlog_reader", "Memlog Reader", [
            "read" => true,
            "read_private_posts" => true,
        ]);
    }
    echo "Roles ready\n";
    ' 2>/dev/null || log_warn "  Roles may already exist"
    log_ok "Custom roles: memlog_writer, memlog_reader"

    # Create service users
    log_info "Creating service users..."
    local wp_apppw
    wp_apppw=$(grep WP_ADMIN_PASSWORD "$ENV_FILE" | cut -d= -f2)

    if ! $wp user get memlog-writer --field=login 2>/dev/null | grep -q "memlog-writer"; then
        $wp user create memlog-writer writer@wp-memlog.local --role=memlog_writer --user_pass="$(gen_password)" 2>/dev/null
        log_ok "  user: memlog-writer"
    else
        log_ok "  user: memlog-writer (exists)"
    fi

    if ! $wp user get memlog-reader --field=login 2>/dev/null | grep -q "memlog-reader"; then
        $wp user create memlog-reader reader@wp-memlog.local --role=memlog_reader --user_pass="$(gen_password)" 2>/dev/null
        log_ok "  user: memlog-reader"
    else
        log_ok "  user: memlog-reader (exists)"
    fi

    # Install mu-plugins
    log_info "Installing must-use plugins..."
    local mu_dir="/var/www/html/wp-content/mu-plugins"
    docker cp "$PROJECT_DIR/wp-content/mu-plugins/memlog-roles.php" "wp-memlog-wp:${mu_dir}/" 2>/dev/null
    docker cp "$PROJECT_DIR/wp-content/mu-plugins/memlog-classifai-auto.php" "wp-memlog-wp:${mu_dir}/" 2>/dev/null
    docker cp "$PROJECT_DIR/wp-content/mu-plugins/memlog-openrouter.php" "wp-memlog-wp:${mu_dir}/" 2>/dev/null
    log_ok "mu-plugins installed"
}

# ── Step 4: Meilisearch index ──────────────────────────
setup_meilisearch() {
    log_step "Step 4: Meilisearch index setup"

    local meili_url meili_key
    meili_url=$(grep WP_MEMLOG_MEILI_URL "$ENV_FILE" | cut -d= -f2)
    meili_key=$(grep MEILI_MASTER_KEY "$ENV_FILE" | cut -d= -f2)

    # Wait for Meilisearch
    log_info "Waiting for Meilisearch..."
    local max_wait=30 waited=0
    while [[ $waited -lt $max_wait ]]; do
        if curl -sf "${meili_url}/health" &>/dev/null; then
            break
        fi
        sleep 2
        waited=$((waited + 2))
    done

    # Create index
    log_info "Creating wp_posts index..."
    curl -sf -X POST "${meili_url}/indexes" \
        -H "Authorization: Bearer ${meili_key}" \
        -H "Content-Type: application/json" \
        -d '{"uid": "wp_posts", "primaryKey": "id"}' 2>/dev/null \
        && log_ok "Index created" || log_warn "Index may already exist"

    # Configure settings
    log_info "Configuring index settings..."
    curl -sf -X PATCH "${meili_url}/indexes/wp_posts/settings" \
        -H "Authorization: Bearer ${meili_key}" \
        -H "Content-Type: application/json" \
        -d '{
            "filterableAttributes": ["categories", "tags", "status", "date", "_enriched"],
            "sortableAttributes": ["date"],
            "searchableAttributes": ["title", "content", "excerpt"],
            "displayedAttributes": ["title", "content", "excerpt", "categories", "tags", "date", "status", "_enriched"]
        }' 2>/dev/null && log_ok "Index settings applied"

    # Create search API key
    log_info "Creating search API key..."
    curl -sf -X POST "${meili_url}/keys" \
        -H "Authorization: Bearer ${meili_key}" \
        -H "Content-Type: application/json" \
        -d '{
            "name": "agent_search",
            "description": "Search-only for agents",
            "actions": ["search"],
            "indexes": ["wp_posts"],
            "expiresAt": null
        }' 2>/dev/null && log_ok "Search API key created"

    log_ok "Meilisearch ready"
}

# ── Step 5: Python package ─────────────────────────────
setup_python() {
    log_step "Step 5: Python package installation"

    cd "$PROJECT_DIR"

    # Create venv if needed
    if [[ ! -d "$PROJECT_DIR/.venv" ]]; then
        log_info "Creating Python virtual environment..."
        python3 -m venv "$PROJECT_DIR/.venv"
        log_ok "venv created"
    fi

    log_info "Installing Python dependencies..."
    "$PROJECT_DIR/.venv/bin/pip" install -e "$PROJECT_DIR" 2>&1 | tail -3
    log_ok "Python package installed"

    # Quick import test
    if "$PROJECT_DIR/.venv/bin/python3" -c "from wp_memlog import session, client, embedder, indexer; print('OK')" 2>/dev/null; then
        log_ok "Import test passed"
    else
        log_warn "Import test failed — check dependencies"
    fi
}

# ── Step 6: Verification ───────────────────────────────
run_verification() {
    log_step "Step 6: Verification"

    local pass=0 fail=0 total=0
    local wp="docker exec wp-memlog-wp wp --allow-root"

    check() {
        local name=$1; local cmd=$2
        total=$((total + 1))
        if eval "$cmd" &>/dev/null; then
            log_ok "  ✓ $name"
            pass=$((pass + 1))
        else
            log_error "  ✗ $name"
            fail=$((fail + 1))
        fi
    }

    echo ""
    check "Docker containers healthy" \
        "docker inspect --format='{{.State.Health.Status}}' wp-memlog-wp | grep -q healthy"
    check "WordPress installed" \
        "$wp core is-installed"
    check "Categories exist (deus)" \
        "$wp term list category --slug=deus --field=slug | grep -q deus"
    role_check() { $wp eval "echo get_role('$1') ? 'ok' : 'fail';" 2>/dev/null | grep -q ok; }
    check "Custom roles exist" \
        "role_check memlog_writer"
    check "Meilisearch healthy" \
        "curl -sf http://127.0.0.1:7700/health | grep -q available"
    check "Meilisearch index exists" \
        "curl -sf -H \"Authorization: Bearer $(grep MEILI_MASTER_KEY "$ENV_FILE" | cut -d= -f2)\" http://127.0.0.1:7700/indexes/wp_posts/stats | grep -q numberOfDocuments"
    check "Python package imports" \
        "$PROJECT_DIR/.venv/bin/python3 -c 'from wp_memlog import session, client, embedder, indexer' 2>/dev/null"
    check "CLI post command" \
        "$PROJECT_DIR/.venv/bin/python3 src/wp_memlog_cli.py post --agent test --date 2026-01-01 --content 'setup verification' --title '[test] setup' 2>&1 | grep -q 'Indexed'"
    check "CLI search command" \
        "$PROJECT_DIR/.venv/bin/python3 src/wp_memlog_cli.py search 'setup' --limit 1 2>&1 | grep -q result"

    echo ""
    echo -e "${BOLD}Results: ${GREEN}${pass} passed${NC} / ${RED}${fail} failed${NC} / ${total} total${NC}"

    if [[ $fail -gt 0 ]]; then
        log_warn "Some checks failed. Run ./scripts/doctor.sh for details."
    else
        log_ok "All checks passed! 🎯"
    fi
}

# ── Summary ────────────────────────────────────────────
print_summary() {
    local wp_url wp_user wp_pass
    wp_url=$(grep WP_MEMLOG_WP_URL "$ENV_FILE" | cut -d= -f2)
    wp_user="admin"
    wp_pass=$(grep WP_ADMIN_PASSWORD "$ENV_FILE" | cut -d= -f2)

    echo ""
    echo -e "${BOLD}${GREEN}╔══════════════════════════════════════════════╗${NC}"
    echo -e "${BOLD}${GREEN}║       wp-memlog setup complete! 🎯           ║${NC}"
    echo -e "${BOLD}${GREEN}╚══════════════════════════════════════════════╝${NC}"
    echo ""
    echo -e "  ${BOLD}WordPress:${NC}  ${wp_url}/wp-admin"
    echo -e "  ${BOLD}Username:${NC}   ${wp_user}"
    echo -e "  ${BOLD}Password:${NC}   ${wp_pass}"
    echo -e "  ${BOLD}Meilisearch:${NC} http://127.0.0.1:7700"
    echo ""
    echo -e "  ${BOLD}Quick commands:${NC}"
    echo -e "    ${CYAN}Post session:${NC}"
    echo -e "      .venv/bin/python3 src/wp_memlog_cli.py post \\"
    echo -e "        --agent hermes --date 2026-01-01 \\"
    echo -e "        --content 'Session content' --title 'Title'"
    echo ""
    echo -e "    ${CYAN}Search:${NC}"
    echo -e "      .venv/bin/python3 src/wp_memlog_cli.py search 'query'"
    echo ""
    echo -e "    ${CYAN}Collect:${NC}"
    echo -e "      .venv/bin/python3 src/collector_cli.py --config config/agents.yaml collect hermes"
