    echo -e "    ${CYAN}Diagnose:${NC}"
    echo -e "      ./scripts/doctor.sh"
    echo ""
}

# ── Reset ──────────────────────────────────────────────
do_reset() {
    log_step "⚠️  RESET — This will DELETE all data!"
    read -rp "Type 'DELETE' to confirm: " ans
    if [[ "$ans" != "DELETE" ]]; then
        log_info "Reset cancelled"
        return 0
    fi

    cd "$PROJECT_DIR"
    docker compose down -v 2>&1 | tail -3
    rm -f "$ENV_FILE"
    log_ok "All containers, volumes, and .env removed"
    log_info "Run setup.sh again to start fresh"
}

# ── Main ───────────────────────────────────────────────
main() {
    echo -e "${BOLD}${CYAN}"
    echo "  ╔═══════════════════════════════════════╗"
    echo "  ║   wp-memlog — One-Command Setup      ║"
    echo "  ╚═══════════════════════════════════════╝"
    echo -e "${NC}"

    local mode="${1:-full}"

    case "$mode" in
        --reset)
            preflight
            do_reset
            return
            ;;
        --quick)
            preflight
            setup_docker
            setup_meilisearch
            setup_python
            run_verification
            print_summary
            ;;
        --full|*)
            preflight
            setup_env
            setup_docker
            setup_wordpress
            setup_meilisearch
            setup_python
            run_verification
            print_summary
            ;;
    esac
}

main "$@"
